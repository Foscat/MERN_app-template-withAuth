/**
 * Deterministic module-per-file JSDoc documentation generator.
 *
 * @module scripts/docs/generate-docs
 */

import { constants as fsConstants } from "node:fs";
import { createHash } from "node:crypto";
import {
  access,
  mkdir,
  readFile,
  readdir,
  unlink,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const jsdoc2md = require("jsdoc-to-markdown");
const GENERATED_NOTICE =
  "<!-- Generated by scripts/docs/generate-docs.mjs. Do not edit directly. -->";

/**
 * Description of a documented source module.
 *
 * @typedef {Object} DocumentationModule
 * @property {"backend"|"client"} scope Documentation collection.
 * @property {string} source Repository-relative source path.
 * @property {string} output Repository-relative Markdown output path.
 * @property {string} [sourceSha256] Source content fingerprint.
 * @property {string} [documentationSha256] Generated page fingerprint.
 */

/**
 * Convert an operating-system path to a repository-stable POSIX path.
 *
 * @param {string} value Path to normalize.
 * @returns {string} Normalized path.
 */
function toPosixPath(value) {
  return value.split(path.sep).join("/");
}

/**
 * Create a lowercase SHA-256 fingerprint for deterministic drift metadata.
 *
 * @param {string} contents Content to fingerprint.
 * @returns {string} Hex-encoded SHA-256 digest.
 */
function sha256(contents) {
  return createHash("sha256").update(contents, "utf8").digest("hex");
}

/**
 * Determine whether a path exists.
 *
 * @param {string} targetPath Absolute path to inspect.
 * @returns {Promise<boolean>} Whether the target exists.
 */
async function pathExists(targetPath) {
  try {
    await access(targetPath, fsConstants.F_OK);
    return true;
  } catch {
    return false;
  }
}

/**
 * Recursively collect JavaScript source paths below a directory.
 *
 * @param {string} directory Absolute directory path.
 * @returns {Promise<string[]>} Sorted absolute source paths.
 */
async function walkJavaScriptFiles(directory) {
  if (!(await pathExists(directory))) {
    return [];
  }

  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries.sort((left, right) =>
    left.name.localeCompare(right.name),
  )) {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      files.push(...(await walkJavaScriptFiles(entryPath)));
    } else if (/\.(?:js|jsx|cjs|mjs)$/.test(entry.name)) {
      files.push(entryPath);
    }
  }

  return files;
}

/**
 * Identify test-only files that should not appear in public API references.
 *
 * @param {string} relativePath Repository-relative source path.
 * @returns {boolean} Whether the path is test-only.
 */
function isTestSource(relativePath) {
  return (
    /(?:^|\/)(?:test|tests|__tests__)(?:\/|$)/.test(relativePath) ||
    /\.(?:test|spec)\.(?:js|jsx|cjs|mjs)$/.test(relativePath)
  );
}

/**
 * Discover documentable backend and client modules.
 *
 * @param {string} rootDir Absolute repository root.
 * @returns {Promise<DocumentationModule[]>} Stable source-to-output mappings.
 */
export async function discoverDocumentationModules(rootDir) {
  const absoluteRoot = path.resolve(rootDir);
  const sourcePaths = [];
  const serverPath = path.join(absoluteRoot, "server.js");

  if (await pathExists(serverPath)) {
    sourcePaths.push(serverPath);
  }

  sourcePaths.push(
    ...(await walkJavaScriptFiles(path.join(absoluteRoot, "app"))),
    ...(await walkJavaScriptFiles(path.join(absoluteRoot, "client", "src"))),
    ...(await walkJavaScriptFiles(path.join(absoluteRoot, "shared"))),
    ...(await walkJavaScriptFiles(path.join(absoluteRoot, "scripts"))),
  );

  return sourcePaths
    .map((sourcePath) => toPosixPath(path.relative(absoluteRoot, sourcePath)))
    .filter((source) => !isTestSource(source))
    .sort((left, right) => left.localeCompare(right))
    .map((source) => {
      const isClient = source.startsWith("client/src/");
      const scope = isClient ? "client" : "backend";
      const scopedSource = isClient
        ? source.slice("client/src/".length)
        : source;

      return {
        scope,
        source,
        output: `docs/generated/${scope}/${scopedSource}.md`,
      };
    });
}

/**
 * Render one source file through jsdoc-to-markdown.
 *
 * @param {string} sourcePath Absolute source path.
 * @returns {Promise<string>} Rendered Markdown.
 */
async function renderJSDocSource(sourcePath) {
  return jsdoc2md.render({ source: await readFile(sourcePath, "utf8") });
}

/**
 * Build the Markdown page for one source module.
 *
 * @param {DocumentationModule} module Documented module metadata.
 * @param {string} renderedJSDoc Rendered JSDoc Markdown.
 * @returns {string} Complete generated page.
 */
function renderModulePage(module, renderedJSDoc) {
  const sourceLink = path.posix.relative(
    path.posix.dirname(module.output),
    module.source,
  );
  const reference =
    renderedJSDoc.trim().replace(/[\t ]+$/gm, "") ||
    "_No public JSDoc symbols found._";

  return `${GENERATED_NOTICE}\n\n# \`${module.source}\`\n\n[View source](${sourceLink})\n\n${reference}\n`;
}

/**
 * Render a collection index.
 *
 * @param {"backend"|"client"} scope Documentation collection.
 * @param {DocumentationModule[]} modules Modules belonging to the collection.
 * @returns {string} Generated collection index.
 */
function renderCollectionIndex(scope, modules) {
  const title =
    scope === "backend" ? "Backend API reference" : "Client reference";
  const description =
    scope === "backend"
      ? "Server bootstrap, controllers, middleware, models, and route modules."
      : "Application entrypoints, API utilities, contexts, layouts, pages, and components.";
  const items = modules
    .map((module) => {
      const link = path.posix.relative(
        `docs/generated/${scope}`,
        module.output,
      );
      return `- [\`${module.source}\`](${link})`;
    })
    .join("\n");

  return `${GENERATED_NOTICE}\n\n# ${title}\n\n${description}\n\n${items}\n`;
}

/**
 * Render a compatibility index at a historical documentation path.
 *
 * @param {"backend"|"client"} scope Documentation collection.
 * @param {DocumentationModule[]} modules Modules belonging to the collection.
 * @returns {string} Generated compatibility index.
 */
function renderCompatibilityIndex(scope, modules) {
  const title =
    scope === "backend" ? "API reference" : "Client component reference";
  const collectionPath = `generated/${scope}/README.md`;
  const items = modules
    .map((module) => {
      const link = path.posix.relative("docs", module.output);
      return `- [\`${module.source}\`](${link})`;
    })
    .join("\n");

  return `${GENERATED_NOTICE}\n\n# ${title}\n\nThis index preserves the established documentation entrypoint. See the [granular ${scope} index](${collectionPath}) or open a module directly.\n\n${items}\n`;
}

/**
 * Render the top-level generated documentation index.
 *
 * @param {number} backendCount Number of backend module pages.
 * @param {number} clientCount Number of client module pages.
 * @returns {string} Generated documentation landing page.
 */
function renderRootIndex(backendCount, clientCount) {
  return `${GENERATED_NOTICE}\n\n# Generated documentation\n\nJSDoc is rendered into one Markdown page per source module so reviews and drift checks remain focused.\n\n- [Backend API reference](backend/README.md) (${backendCount} modules)\n- [Client reference](client/README.md) (${clientCount} modules)\n\nRun \`npm run docs:generate\` to rebuild these files or \`npm run docs:check\` to verify them without writing.\n`;
}

/**
 * Create every expected generated documentation file in memory.
 *
 * @param {Object} options Generator options.
 * @param {string} options.rootDir Absolute repository root.
 * @param {function(string): Promise<string>} [options.renderSource] JSDoc renderer override.
 * @returns {Promise<Map<string, string>>} Repository-relative output paths and contents.
 */
export async function createDocumentationPlan({
  rootDir,
  renderSource = renderJSDocSource,
}) {
  const absoluteRoot = path.resolve(rootDir);
  const discoveredModules = await discoverDocumentationModules(absoluteRoot);
  const modules = [];
  const plan = new Map();

  for (const module of discoveredModules) {
    const sourcePath = path.join(absoluteRoot, ...module.source.split("/"));
    const [sourceContents, renderedJSDoc] = await Promise.all([
      readFile(sourcePath, "utf8"),
      renderSource(sourcePath),
    ]);
    const page = renderModulePage(module, renderedJSDoc);
    const documentedModule = {
      ...module,
      sourceSha256: sha256(sourceContents),
      documentationSha256: sha256(page),
    };

    modules.push(documentedModule);
    plan.set(module.output, page);
  }

  const backendModules = modules.filter(({ scope }) => scope === "backend");
  const clientModules = modules.filter(({ scope }) => scope === "client");

  plan.set(
    "docs/generated/backend/README.md",
    renderCollectionIndex("backend", backendModules),
  );
  plan.set(
    "docs/generated/client/README.md",
    renderCollectionIndex("client", clientModules),
  );
  plan.set(
    "docs/api-reference.md",
    renderCompatibilityIndex("backend", backendModules),
  );
  plan.set(
    "docs/client-components.md",
    renderCompatibilityIndex("client", clientModules),
  );
  plan.set(
    "docs/generated/README.md",
    renderRootIndex(backendModules.length, clientModules.length),
  );
  plan.set(
    "docs/generated/manifest.json",
    `${JSON.stringify(
      {
        schemaVersion: 1,
        generator: "scripts/docs/generate-docs.mjs",
        modules,
      },
      null,
      2,
    )}\n`,
  );

  return plan;
}

/**
 * Collect generated files already present on disk.
 *
 * @param {string} generatedRoot Absolute generated documentation directory.
 * @returns {Promise<string[]>} Absolute file paths.
 */
async function collectGeneratedFiles(generatedRoot) {
  if (!(await pathExists(generatedRoot))) {
    return [];
  }

  const entries = await readdir(generatedRoot, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const entryPath = path.join(generatedRoot, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await collectGeneratedFiles(entryPath)));
    } else {
      files.push(entryPath);
    }
  }

  return files;
}

/**
 * Write a documentation plan and remove orphaned generated files.
 *
 * @param {string} rootDir Absolute repository root.
 * @param {Map<string, string>} plan Expected generated files.
 * @returns {Promise<{updated: number, unchanged: number, removed: number}>} Write summary.
 */
export async function writeDocumentationPlan(rootDir, plan) {
  const absoluteRoot = path.resolve(rootDir);
  const generatedRoot = path.join(absoluteRoot, "docs", "generated");
  const expectedPaths = new Set(
    [...plan.keys()].map((output) => path.resolve(absoluteRoot, output)),
  );
  const existingGeneratedFiles = await collectGeneratedFiles(generatedRoot);
  let updated = 0;
  let unchanged = 0;
  let removed = 0;

  for (const filePath of existingGeneratedFiles) {
    if (!expectedPaths.has(path.resolve(filePath))) {
      await unlink(filePath);
      removed += 1;
    }
  }

  for (const [output, contents] of plan) {
    const outputPath = path.resolve(absoluteRoot, output);
    if (
      (await pathExists(outputPath)) &&
      (await readFile(outputPath, "utf8")) === contents
    ) {
      unchanged += 1;
      continue;
    }

    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, contents, "utf8");
    updated += 1;
  }

  return { updated, unchanged, removed };
}

/**
 * Compare the expected plan with generated files on disk.
 *
 * @param {string} rootDir Absolute repository root.
 * @param {Map<string, string>} plan Expected generated files.
 * @returns {Promise<string[]>} Human-readable drift findings.
 */
export async function findDocumentationDrift(rootDir, plan) {
  const absoluteRoot = path.resolve(rootDir);
  const findings = [];

  for (const [output, expectedContents] of plan) {
    const outputPath = path.resolve(absoluteRoot, output);
    if (!(await pathExists(outputPath))) {
      findings.push(`missing: ${output}`);
      continue;
    }

    const actualContents = await readFile(outputPath, "utf8");
    if (actualContents !== expectedContents) {
      findings.push(`changed: ${output}`);
    }
  }

  const expectedPaths = new Set(
    [...plan.keys()].map((output) => path.resolve(absoluteRoot, output)),
  );
  const existingGeneratedFiles = await collectGeneratedFiles(
    path.join(absoluteRoot, "docs", "generated"),
  );

  for (const filePath of existingGeneratedFiles) {
    if (!expectedPaths.has(path.resolve(filePath))) {
      findings.push(
        `orphaned: ${toPosixPath(path.relative(absoluteRoot, filePath))}`,
      );
    }
  }

  return findings.sort((left, right) => left.localeCompare(right));
}

/**
 * Execute the documentation generator command-line interface.
 *
 * @returns {Promise<void>} Resolves when generation or verification completes.
 */
async function main() {
  const rootDir = process.cwd();
  const checkOnly = process.argv.slice(2).includes("--check");
  const plan = await createDocumentationPlan({ rootDir });
  const manifest = JSON.parse(plan.get("docs/generated/manifest.json"));

  if (checkOnly) {
    const findings = await findDocumentationDrift(rootDir, plan);
    if (findings.length > 0) {
      console.error("Generated documentation is out of date:");
      for (const finding of findings) {
        console.error(`- ${finding}`);
      }
      process.exitCode = 1;
      return;
    }

    console.log(
      `Generated documentation is current (${manifest.modules.length} modules, ${plan.size} files).`,
    );
    return;
  }

  const result = await writeDocumentationPlan(rootDir, plan);
  console.log(
    `Generated ${manifest.modules.length} module pages across ${plan.size} files (${result.updated} updated, ${result.unchanged} unchanged${
      result.removed > 0 ? `; removed ${result.removed} orphaned files` : ""
    }).`,
  );
}

const isMainModule =
  process.argv[1] &&
  path.resolve(process.argv[1]) ===
    path.resolve(fileURLToPath(import.meta.url));

if (isMainModule) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
